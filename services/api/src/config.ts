import { z } from "zod";
import { DEFAULT_API_HOST, DEFAULT_API_PORT } from "@clipforge/shared";
import { defaultDatabasePath } from "@clipforge/database";

const LOOPBACK_HOSTS = ["127.0.0.1", "::1", "localhost"] as const;

const envSchema = z.object({
  NODE_ENV: z.enum(["development", "test", "production"]).default("development"),
  // Loopback only: even with request signing, the API is never reachable from the network.
  CLIPFORGE_API_HOST: z.enum(LOOPBACK_HOSTS).default(DEFAULT_API_HOST),
  CLIPFORGE_API_PORT: z.coerce.number().int().min(1024).max(65535).default(DEFAULT_API_PORT),
  CLIPFORGE_LOG_LEVEL: z.enum(["fatal", "error", "warn", "info", "debug", "trace"]).default("info"),
  CLIPFORGE_DATABASE_PATH: z.string().min(1).optional(),
  // Per-launch session secret generated by the desktop runtime (ADR-010). Never logged or persisted.
  CLIPFORGE_API_SECRET: z
    .string({
      error: "missing: the API must be started by the desktop app (see docs/DEVELOPMENT.md)",
    })
    .regex(/^[0-9a-f]{64}$/, "must be 64 lowercase hex characters"),
  // PID of the owning desktop process; the API exits when it disappears (orphan protection).
  CLIPFORGE_PARENT_PID: z.coerce.number().int().positive().optional(),
  CLIPFORGE_JOB_CONCURRENCY: z.coerce.number().int().min(1).max(4).default(1),
  CLIPFORGE_JOB_MAX_QUEUED: z.coerce.number().int().min(1).max(10_000).default(500),
});

export interface ApiConfig {
  readonly env: "development" | "test" | "production";
  readonly host: string;
  readonly port: number;
  readonly logLevel: string;
  readonly databasePath: string;
  readonly secret: Buffer;
  readonly parentPid: number | undefined;
  readonly jobConcurrency: number;
  readonly maxQueuedJobs: number;
}

/** Validates environment once at startup; throws with every problem listed (never the values). */
export function loadConfig(env: NodeJS.ProcessEnv = process.env): ApiConfig {
  const result = envSchema.safeParse(env);
  if (!result.success) {
    throw new Error(`Invalid API configuration:\n${z.prettifyError(result.error)}`);
  }
  const e = result.data;
  return {
    env: e.NODE_ENV,
    host: e.CLIPFORGE_API_HOST,
    port: e.CLIPFORGE_API_PORT,
    logLevel: e.CLIPFORGE_LOG_LEVEL,
    databasePath: e.CLIPFORGE_DATABASE_PATH ?? defaultDatabasePath(env),
    secret: Buffer.from(e.CLIPFORGE_API_SECRET, "hex"),
    parentPid: e.CLIPFORGE_PARENT_PID,
    jobConcurrency: e.CLIPFORGE_JOB_CONCURRENCY,
    maxQueuedJobs: e.CLIPFORGE_JOB_MAX_QUEUED,
  };
}
